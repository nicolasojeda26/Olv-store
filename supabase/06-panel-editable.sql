-- ---------- Promociones automáticas ----------
-- scope: 'all' (toda la tienda), 'category' (una categoría), 'product' (un producto)
-- min_items > 0: promo por cantidad ("llevando 3 o más, 10% OFF") sobre todo el pedido
create table if not exists public.promotions (
  id          bigint generated by default as identity primary key,
  title       text not null check (length(trim(title)) between 2 and 80),
  pct         int  not null check (pct between 1 and 90),
  scope       text not null default 'all' check (scope in ('all','category','product')),
  category    text references public.categories(name) on update cascade on delete cascade,
  product_id  bigint references public.products(id) on delete cascade,
  min_items   int  not null default 0 check (min_items between 0 and 50),
  starts_at   timestamptz,
  ends_at     timestamptz,
  active      boolean not null default true,
  in_ribbon   boolean not null default true,    -- se anuncia en la cinta de arriba
  created_at  timestamptz not null default now(),
  check (scope <> 'category' or category is not null),
  check (scope <> 'product'  or product_id is not null)
);
alter table public.promotions enable row level security;
drop policy if exists "todos ven promociones" on public.promotions;
drop policy if exists "dueña maneja promociones" on public.promotions;
create policy "todos ven promociones"    on public.promotions for select to anon, authenticated using (true);
create policy "dueña maneja promociones" on public.promotions for all to authenticated using (true) with check (true);

-- ---------- Cupones ----------
-- No se pueden listar desde la tienda (el público no los ve); se validan en el servidor.
create table if not exists public.coupons (
  code        text primary key check (code = upper(code) and code ~ '^[A-Z0-9_-]{3,20}$'),
  pct         int  not null check (pct between 1 and 90),
  min_amount  int  not null default 0 check (min_amount >= 0),
  starts_at   timestamptz,
  ends_at     timestamptz,
  max_uses    int  check (max_uses is null or max_uses > 0),
  uses        int  not null default 0,
  active      boolean not null default true,
  note        text,
  created_at  timestamptz not null default now()
);
alter table public.coupons enable row level security;
drop policy if exists "dueña maneja cupones" on public.coupons;
create policy "dueña maneja cupones" on public.coupons for all to authenticated using (true) with check (true);

-- Suma un uso al cupón de forma segura (lo llama el servidor al crear el pedido).
create or replace function public.use_coupon(p_code text) returns boolean
language plpgsql security definer set search_path = public as $$
declare ok boolean;
begin
  update public.coupons set uses = uses + 1
   where code = upper(p_code) and active
     and (max_uses is null or uses < max_uses)
     and (starts_at is null or starts_at <= now())
     and (ends_at is null or ends_at >= now())
  returning true into ok;
  return coalesce(ok, false);
end $$;
revoke all on function public.use_coupon(text) from public, anon, authenticated;

