-- ---------- Productos ----------
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  category    text        not null check (category in ('Maquillaje','Skincare','Combos y regalos','Pestañas','Insumos de uñas','Insumos de pestañas','Accesorios','Brochas y pinceles','Productos capilares','Productos corporales','Fragancias','Aparatología','Librería','Outlet calzado')),
  price       integer     not null check (price > 0),          -- en pesos, sin decimales
  old_price   integer              check (old_price is null or old_price > 0),
  sizes       jsonb       not null default '{"Único":0}'::jsonb, -- {"36":1,"37":0} o {"Único":5}
  image_url   text,
  icon        text        not null default 'sparkles',          -- ícono si no hay foto
  active      boolean     not null default true,
  sort        integer     not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------- Pedidos ----------
create table if not exists public.orders (
  id             uuid        primary key default gen_random_uuid(),
  created_at     timestamptz not null default now(),
  status         text        not null default 'pending'
                 check (status in ('pending','paid','rejected','cancelled','delivered')),
  stock_applied  boolean     not null default false,
  stock_issue    boolean     not null default false,   -- se pagó algo que ya no tenía stock
  items          jsonb       not null,                 -- [{id,name,size,qty,price}]
  total          integer     not null,
  shipping       text        not null,                 -- pickup | city | country
  pay_method     text        not null default 'mercadopago'
                 check (pay_method in ('mercadopago','transfer','cash')),
  buyer_name     text        not null,
  buyer_phone    text        not null,
  buyer_email    text,
  buyer_address  text,
  notes          text,
  mp_preference_id text,
  mp_payment_id  text,
  mp_status      text,
  paid_at        timestamptz
);
create index if not exists orders_created_idx on public.orders (created_at desc);

-- ---------- Conexión con Mercado Pago (solo la lee el servidor) ----------
create table if not exists public.mp_connection (
  id             integer     primary key default 1 check (id = 1),
  mp_user_id     text,
  access_token   text        not null,
  refresh_token  text,
  public_key     text,
  live_mode      boolean,
  expires_at     timestamptz,
  updated_at     timestamptz not null default now()
);

-- ---------- Seguridad (RLS) ----------
alter table public.products      enable row level security;
alter table public.orders        enable row level security;
alter table public.mp_connection enable row level security;

-- Cualquiera puede ver los productos activos; solo la dueña (usuaria logueada) los edita.
drop policy if exists "productos visibles"    on public.products;
drop policy if exists "dueña edita productos" on public.products;
create policy "productos visibles" on public.products
  for select using (active or auth.role() = 'authenticated');
create policy "dueña edita productos" on public.products
  for all to authenticated using (true) with check (true);

-- Los pedidos los crea el servidor; la dueña los ve y les cambia el estado.
drop policy if exists "dueña ve pedidos"    on public.orders;
drop policy if exists "dueña edita pedidos" on public.orders;
create policy "dueña ve pedidos" on public.orders
  for select to authenticated using (true);
create policy "dueña edita pedidos" on public.orders
  for update to authenticated using (true) with check (true);

-- mp_connection: sin políticas = nadie desde el navegador. Solo el servidor (service role).

-- updated_at automático
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;
drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();

-- ---------- Descontar stock cuando un pago se aprueba ----------
-- Se ejecuta una sola vez por pedido (stock_applied), aunque Mercado Pago avise varias veces.
create or replace function public.mark_order_paid(p_order uuid, p_payment text, p_status text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  o      public.orders;
  it     jsonb;
  cur    integer;
  issue  boolean := false;
begin
  select * into o from public.orders where id = p_order for update;
  if not found then return 'not_found'; end if;
  if o.stock_applied then
    update public.orders set mp_status = p_status where id = p_order;
    return 'already_applied';
  end if;

  for it in select * from jsonb_array_elements(o.items) loop
    select coalesce((sizes ->> (it->>'size'))::int, 0) into cur
      from public.products where id = (it->>'id')::bigint for update;
    if cur is null or cur < (it->>'qty')::int then issue := true; end if;
    update public.products
       set sizes = jsonb_set(sizes, array[it->>'size'],
                             to_jsonb(greatest(coalesce(cur,0) - (it->>'qty')::int, 0)))
     where id = (it->>'id')::bigint;
  end loop;

  update public.orders
     set status = 'paid', stock_applied = true, stock_issue = issue,
         mp_payment_id = p_payment, mp_status = p_status, paid_at = now()
   where id = p_order;
  return case when issue then 'paid_stock_issue' else 'paid' end;
end $$;

revoke all on function public.mark_order_paid(uuid, text, text) from public, anon, authenticated;

-- ---------- Fotos de productos ----------
insert into storage.buckets (id, name, public)
values ('productos', 'productos', true)
on conflict (id) do nothing;

drop policy if exists "fotos públicas"     on storage.objects;
drop policy if exists "dueña sube fotos"   on storage.objects;
drop policy if exists "dueña borra fotos"  on storage.objects;
create policy "fotos públicas" on storage.objects
  for select using (bucket_id = 'productos');
create policy "dueña sube fotos" on storage.objects
  for insert to authenticated with check (bucket_id = 'productos');
create policy "dueña borra fotos" on storage.objects
  for delete to authenticated using (bucket_id = 'productos');

-- ---------- Botón de arrepentimiento (Res. 424/2020) ----------
create table if not exists public.revocations (
  id          uuid        primary key default gen_random_uuid(),
  code        text        not null unique,
  created_at  timestamptz not null default now(),
  status      text        not null default 'nuevo' check (status in ('nuevo','en_proceso','resuelto')),
  name        text        not null,
  email       text,
  phone       text,
  order_ref   text,
  product     text,
  reason      text
);
create index if not exists revocations_created_idx on public.revocations (created_at desc);

alter table public.revocations enable row level security;
drop policy if exists "dueña ve arrepentimientos"    on public.revocations;
drop policy if exists "dueña edita arrepentimientos" on public.revocations;
create policy "dueña ve arrepentimientos" on public.revocations
  for select to authenticated using (true);
create policy "dueña edita arrepentimientos" on public.revocations
  for update to authenticated using (true) with check (true);
