-- ---------- Promociones y cupones ----------
create table if not exists promotions (
  id          bigint generated by default as identity primary key,
  title       text not null check (length(trim(title)) between 2 and 80),
  pct         int  not null check (pct between 1 and 90),
  scope       text not null default 'all' check (scope in ('all','category','product')),
  category    text references categories(name) on update cascade on delete cascade,
  product_id  bigint references products(id) on delete cascade,
  min_items   int  not null default 0 check (min_items between 0 and 50),
  starts_at   timestamptz,
  ends_at     timestamptz,
  active      boolean not null default true,
  in_ribbon   boolean not null default true,
  created_at  timestamptz not null default now(),
  check (scope <> 'category' or category is not null),
  check (scope <> 'product'  or product_id is not null)
);

create table if not exists coupons (
  code        text primary key check (code = upper(code) and code ~ '^[A-Z0-9_-]{3,20}$'),
  pct         int  not null check (pct between 1 and 90),
  min_amount  int  not null default 0 check (min_amount >= 0),
  starts_at   timestamptz,
  ends_at     timestamptz,
  max_uses    int  check (max_uses is null or max_uses > 0),
  uses        int  not null default 0,
  active      boolean not null default true,
  note        text,
  created_at  timestamptz not null default now()
);

-- Suma un uso al cupón si sigue vigente
create or replace function use_coupon(p_code text) returns boolean
language plpgsql as $$
declare ok boolean;
begin
  update coupons set uses = uses + 1
   where code = upper(p_code) and active
     and (max_uses is null or uses < max_uses)
     and (starts_at is null or starts_at <= now())
     and (ends_at is null or ends_at >= now())
  returning true into ok;
  return coalesce(ok, false);
end $$;

-- Marca un pedido como pagado y descuenta el stock (una sola vez)
create or replace function mark_order_paid(p_order uuid, p_payment text, p_status text) returns text
language plpgsql as $$
declare
  o      orders;
  it     jsonb;
  cur    integer;
  issue  boolean := false;
begin
  select * into o from orders where id = p_order for update;
  if not found then return 'not_found'; end if;
  if o.stock_applied then
    update orders set mp_status = p_status where id = p_order;
    return 'already_applied';
  end if;
  for it in select * from jsonb_array_elements(o.items) loop
    select coalesce((sizes ->> (it->>'size'))::int, 0) into cur
      from products where id = (it->>'id')::bigint for update;
    if cur is null or cur < (it->>'qty')::int then issue := true; end if;
    update products
       set sizes = jsonb_set(sizes, array[it->>'size'], to_jsonb(greatest(coalesce(cur,0) - (it->>'qty')::int, 0)))
     where id = (it->>'id')::bigint;
  end loop;
  update orders
     set status = 'paid', stock_applied = true, stock_issue = issue,
         mp_payment_id = p_payment, mp_status = p_status, paid_at = now()
   where id = p_order;
  return case when issue then 'paid_stock_issue' else 'paid' end;
end $$;

-- ---------- Login propio del panel ----------
-- Las contraseñas se guardan cifradas (bcrypt), nunca en texto.
create table if not exists admins (
  email          text primary key check (email = lower(email)),
  password_hash  text,
  created_at     timestamptz not null default now(),
  last_login_at  timestamptz
);
-- Sesiones abiertas (se guarda solo un resumen del código, no el código)
create table if not exists admin_sessions (
  token_hash  text primary key,
  email       text not null references admins(email) on delete cascade on update cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null
);
create index if not exists admin_sessions_email_idx on admin_sessions (email);
-- Enlaces de "Olvidé mi contraseña"
create table if not exists password_resets (
  token_hash  text primary key,
  email       text not null references admins(email) on delete cascade on update cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  used_at     timestamptz
);
