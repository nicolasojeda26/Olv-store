-- ---------- Categorías ----------
create table if not exists categories (
  name         text primary key check (length(trim(name)) between 2 and 40),
  description  text not null default '',
  icon         text not null default 'sparkles',
  hue          int  not null default 330 check (hue between 0 and 360),
  image_url    text,
  sort         int  not null default 0,
  active       boolean not null default true,
  in_nav       boolean not null default false,
  updated_at   timestamptz not null default now()
);

-- ---------- Productos ----------
create table if not exists products (
  id              bigint generated by default as identity primary key,
  name            text        not null,
  category        text        not null references categories(name) on update cascade on delete restrict,
  price           integer     not null check (price > 0),
  old_price       integer     check (old_price is null or old_price > 0),
  sizes           jsonb       not null default '{"Único":0}'::jsonb,   -- stock por opción: {"Único":5} o {"Rojo 01":2}
  image_url       text,                                                -- foto principal
  images          text[]      not null default '{}',                   -- fotos extra
  variant_label   text        not null default 'Talle'
                  check (variant_label in ('Talle','Número','Tono','Color','Modelo','Aroma')),
  variant_images  jsonb       not null default '{}'::jsonb,            -- foto de cada opción
  icon            text        not null default 'sparkles',
  active          boolean     not null default true,
  sort            integer     not null default 0,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create or replace function touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;
drop trigger if exists products_touch on products;
create trigger products_touch before update on products for each row execute function touch_updated_at();

-- ---------- Pedidos ----------
create table if not exists orders (
  id               uuid        primary key default gen_random_uuid(),
  created_at       timestamptz not null default now(),
  status           text        not null default 'pending'
                   check (status in ('pending','paid','rejected','cancelled','delivered')),
  stock_applied    boolean     not null default false,
  stock_issue      boolean     not null default false,
  items            jsonb       not null,
  total            integer     not null,
  discount         integer     not null default 0,     -- descuento por transferencia
  subtotal         integer,
  promo_discount   integer     not null default 0,
  coupon           text,
  coupon_discount  integer     not null default 0,
  shipping         text        not null,
  pay_method       text        not null default 'mercadopago' check (pay_method in ('mercadopago','transfer','cash')),
  buyer_name       text        not null,
  buyer_phone      text        not null,
  buyer_email      text,
  buyer_address    text,
  notes            text,
  mp_preference_id text,
  mp_payment_id    text,
  mp_status        text,
  paid_at          timestamptz
);
create index if not exists orders_created_idx on orders (created_at desc);

